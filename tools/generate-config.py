#!/usr/bin/env python3
"""Compile validated JSON-subset YAML into non-executable AHK runtime data."""
import argparse
import hashlib
import json
from pathlib import Path
import sys

from macflow_config import ConfigError, load_and_validate


def build_outputs(root):
    root = Path(root)
    bundle = load_and_validate(root)
    sources = {
        name: hashlib.sha256((root / "config" / name).read_bytes()).hexdigest()
        for name in ("schema.json", "mappings.yaml", "apps.yaml", "release.yaml")
    }
    source_hash = hashlib.sha256(json.dumps(sources, sort_keys=True).encode()).hexdigest()
    mappings = sorted(bundle["mappings"]["mappings"], key=lambda rule: rule["id"])
    apps = bundle["apps"]
    profiles = sorted(apps["profiles"], key=lambda profile: profile["id"])
    lines = ["; Generated by tools/generate-config.py. DO NOT EDIT.", "[meta]"]

    def field(key, value):
        if isinstance(value, bool):
            value = "1" if value else "0"
        elif isinstance(value, list):
            value = "|".join(value)
        value = str(value)
        if any(char in value for char in "\r\n\0"):
            raise ConfigError("INI values must be single-line data: " + key)
        lines.append(key + "=" + value)

    for key, value in (
        ("schema_version", 1), ("delivery_status", "DEVELOPMENT PREVIEW"),
        ("mode", "ahk-only"), ("source_hash", source_hash),
        ("rule_count", len(mappings)), ("profile_count", len(profiles)),
        ("allowed_hkls", apps["allowed_hkls"]),
        ("bypass_processes", apps["bypass_processes"]),
    ):
        field(key, value)
    for index, rule in enumerate(mappings, 1):
        lines.extend(["", "[rule.%d]" % index])
        for key in ("id", "enabled", "physical_chord", "contexts", "action", "priority", "blocked_reason"):
            field(key, rule[key])
    for index, profile in enumerate(profiles, 1):
        lines.extend(["", "[profile.%d]" % index])
        for key in ("id", "processes", "contexts", "enabled", "requires_integration"):
            field(key, profile[key])
    # AHK IniRead treats BOM-marked UTF-16 as Unicode; other encodings use ANSI.
    ini = ("\ufeff" + "\r\n".join(lines) + "\r\n").encode("utf-16-le")
    checksum = hashlib.sha256(ini).hexdigest()
    manifest = {
        "schema_version": 1, "delivery_status": "DEVELOPMENT PREVIEW",
        "hardware_validation": "NOT TESTED", "mode": "ahk-only",
        "source_hash": source_hash, "sources": sources,
        "artifacts": {"macflow.ini": checksum},
    }
    return {
        "macflow.ini": ini,
        "macflow.ini.sha256": (checksum + "\n").encode("ascii"),
        "manifest.json": (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode(),
    }


def generate(root, check=False):
    outputs = build_outputs(root)
    target = Path(root) / "build" / "generated"
    stale = []
    for name, data in outputs.items():
        path = target / name
        if check:
            if not path.is_file() or path.read_bytes() != data:
                stale.append(name)
        else:
            target.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    if stale:
        raise ConfigError("Generated artifacts are missing/stale: " + ", ".join(stale))
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--check", action="store_true", help="Verify without writing")
    args = parser.parse_args()
    try:
        outputs = generate(args.root, args.check)
    except (ConfigError, OSError, ValueError) as exc:
        print("Configuration error: " + str(exc), file=sys.stderr)
        return 1
    print(("Verified" if args.check else "Generated") + " %d artifacts; hardware NOT TESTED." % len(outputs))
    return 0


if __name__ == "__main__":
    sys.exit(main())

